# PlatformIO hook: build the web UI into the firmware.
#
# web/index.html is gzipped into a generated header, so `pio run -t upload`
# updates the UI together with the firmware and never touches LittleFS, where
# your recordings and patterns live. The header is only rewritten when the page
# changes, so unrelated builds don't recompile the web server.
Import("env")
import gzip, os

source = os.path.join(env.subst("$PROJECT_DIR"), "web", "index.html")
out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")
header = os.path.join(out_dir, "web_ui.h")

with open(source, "rb") as f:
    packed = gzip.compress(f.read(), 9, mtime=0)   # mtime=0: same page, same bytes
rows = ",\n".join(",".join(str(b) for b in packed[i:i + 32]) for i in range(0, len(packed), 32))
text = ("// Generated by tools/embed_web_ui.py from web/index.html - do not edit.\n"
        "#pragma once\n#include <stdint.h>\n#include <stddef.h>\n"
        "static const uint8_t WEB_UI_GZ[] = {\n%s\n};\n"
        "static const size_t WEB_UI_GZ_LEN = sizeof(WEB_UI_GZ);\n" % rows)

os.makedirs(out_dir, exist_ok=True)
if not os.path.exists(header) or open(header).read() != text:
    with open(header, "w") as f:
        f.write(text)
env.Append(CPPPATH=[out_dir])
print("Kabuto: web UI embedded (%d KB gzipped)" % ((len(packed) + 1023) // 1024))
