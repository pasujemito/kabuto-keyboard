# PlatformIO hook: build update_public_key.pem into the firmware.
#
# Pads only list and install releases signed with the matching private key
# (see tools/release_index.py). Without the file the build still works, but the
# Updates panel says updates are off, so an unsigned build never trusts anything.
Import("env")
import json, os

source = os.path.join(env.subst("$PROJECT_DIR"), "update_public_key.pem")
out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")
header = os.path.join(out_dir, "update_key.h")

pem = ""
if os.path.exists(source):
    with open(source) as f:
        pem = f.read().strip() + "\n"
    if "BEGIN PUBLIC KEY" not in pem:
        print("Kabuto: update_public_key.pem isn't a PEM public key")
        env.Exit(1)
else:
    print("Kabuto: no update_public_key.pem - automatic updates are off in this build")

# json.dumps gives a valid C string literal for PEM text (ASCII, \\n escapes).
text = ("// Generated by tools/embed_update_key.py from update_public_key.pem - do not edit.\n"
        "#pragma once\nstatic const char UPDATE_PUBLIC_KEY[] = %s;\n" % json.dumps(pem))
os.makedirs(out_dir, exist_ok=True)
if not os.path.exists(header) or open(header).read() != text:
    with open(header, "w") as f:
        f.write(text)
env.Append(CPPPATH=[out_dir])
